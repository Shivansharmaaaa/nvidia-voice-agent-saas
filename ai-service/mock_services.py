"""
Mock NVIDIA Model Services
Simple HTTP servers that simulate Nemotron Speech, LLM, and Magpie TTS
for development when actual NVIDIA services are not available
"""

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
import base64
import json
import uvicorn
from typing import Optional

# Mock ASR Service (Port 8001)
asr_app = FastAPI(title="Mock Nemotron Speech ASR")
asr_app.add_middleware(CORSMiddleware, allow_origins=["*"], allow_methods=["*"], allow_headers=["*"])

class ASRRequest(BaseModel):
    audio: str  # base64 encoded audio

@asr_app.post("/transcribe")
async def transcribe(request: ASRRequest):
    """Mock transcription - returns sample text"""
    return {
        "text": "Hello, this is a mock transcription of your audio input.",
        "confidence": 0.95,
        "language": "en-US"
    }

@asr_app.get("/health")
async def health():
    return {"status": "healthy", "service": "mock-nemotron-speech"}

# Mock LLM Service (Port 8002)
llm_app = FastAPI(title="Mock Nemotron LLM")
llm_app.add_middleware(CORSMiddleware, allow_origins=["*"], allow_methods=["*"], allow_headers=["*"])

class LLMRequest(BaseModel):
    messages: list
    temperature: Optional[float] = 0.7
    max_tokens: Optional[int] = 500

@llm_app.post("/generate")
async def generate(request: LLMRequest):
    """Mock LLM response"""
    user_message = request.messages[-1].get("content", "") if request.messages else ""
    return {
        "text": f"I understand you said: '{user_message}'. This is a mock AI response. In production, this would be generated by Nemotron 3 Nano.",
        "tokens": 25,
        "model": "nemotron-3-nano-mock"
    }

@llm_app.get("/health")
async def health():
    return {"status": "healthy", "service": "mock-nemotron-llm"}

# Mock TTS Service (Port 8003)
tts_app = FastAPI(title="Mock Magpie TTS")
tts_app.add_middleware(CORSMiddleware, allow_origins=["*"], allow_methods=["*"], allow_headers=["*"])

class TTSRequest(BaseModel):
    text: str
    voice: Optional[str] = "default"
    speed: Optional[float] = 1.0

@tts_app.post("/synthesize")
async def synthesize(request: TTSRequest):
    """Mock TTS - returns empty audio (frontend will handle gracefully)"""
    # Return a minimal WAV file header (silence)
    # In production, this would be actual synthesized speech
    silent_audio = base64.b64encode(b"RIFF" + b"\x00" * 100).decode()
    return {
        "audio": silent_audio,
        "format": "wav",
        "sample_rate": 16000
    }

@tts_app.get("/health")
async def health():
    return {"status": "healthy", "service": "mock-magpie-tts"}

if __name__ == "__main__":
    import sys
    
    if len(sys.argv) > 1:
        port = int(sys.argv[1])
        if port == 8001:
            uvicorn.run(asr_app, host="0.0.0.0", port=8001)
        elif port == 8002:
            uvicorn.run(llm_app, host="0.0.0.0", port=8002)
        elif port == 8003:
            uvicorn.run(tts_app, host="0.0.0.0", port=8003)
    else:
        print("Usage: python mock_services.py <port>")
        print("  Port 8001: Mock ASR Service")
        print("  Port 8002: Mock LLM Service")
        print("  Port 8003: Mock TTS Service")
